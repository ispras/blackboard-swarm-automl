"""
BMS Molecular Translation — image -> InChI  (final solution, swarm mirfak_mu/dubhe_phi/altair_lambda)

Approach
--------
Character-level image-to-sequence model (encoder-decoder):
  * Encoder: ConvNeXt-Tiny (timm `convnext_tiny.fb_in22k_ft_in1k`), ImageNet-pretrained,
    grayscale replicated to 3 channels, input resized max-side -> 320 with white padding,
    ImageNet normalization inside the encoder, + learned 10x10 positional embedding.
  * Decoder: 6-layer Transformer decoder, d=512, 8 heads, ffn=2048, learned positional
    emb, char vocabulary (38 InChI chars + <pad>/<sos>/<eos>).
  * Targets are the FULL InChI string (prefix "InChI=1S/" is generated by the model).
  * Trained on 1,919,348 images (canonical holdout = 20,000 held out), batch 128,
    bf16 autocast, AdamW (decoder 3e-4 / encoder 1.5e-4), cosine schedule, label
    smoothing 0.1, light geometric+brightness augmentation.

Decoding
--------
Greedy, starting from <sos> WITHOUT forcing the prefix (free generation). Forcing the
prefix costs ~9 mean Levenshtein due to a positional train/inference mismatch; free
generation is correct. max_len 420 (data max 403), batch 512. Batches are sorted by
test-image file size (a proxy for molecule size / InChI length) so early-<eos> breaks
fire sooner. Postprocessing: predictions are re-serialized with RDKit
(MolFromInchi->MolToInchi); this fixes chemically-correct-but-non-canonical strings and
lowers the clean-holdout metric by ~0.2 (it is a no-op on the ground-truth format).

Validation (canonical 20k holdout, disjoint from train): raw greedy mean Levenshtein 2.58;
after RDKit canonicalization 2.35, exact 77%. Independently reproduced (2.307 on 2k).

Usage
-----
    python solution.py --ckpt /path/to/run1_best.pt --data_dir /path/to/data --out submission.csv
"""
import argparse, os, sys, time
import numpy as np, pandas as pd, torch
import cv2
from torch.utils.data import Dataset, DataLoader

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from model_arch import Img2InChI


class ImgDS(Dataset):
    def __init__(self, paths, size):
        self.paths, self.size = paths, size

    def __len__(self):
        return len(self.paths)

    def __getitem__(self, i):
        img = cv2.imread(self.paths[i], cv2.IMREAD_GRAYSCALE)
        h, w = img.shape
        s = self.size / max(h, w)
        nh, nw = max(1, int(round(h * s))), max(1, int(round(w * s)))
        interp = cv2.INTER_AREA if s < 1 else cv2.INTER_LINEAR
        img = cv2.resize(img, (nw, nh), interpolation=interp)
        canvas = np.full((self.size, self.size), 255, np.uint8)
        canvas[:nh, :nw] = img
        return torch.from_numpy(canvas).float().div(255).unsqueeze(0)  # [0,1], 1ch


@torch.no_grad()
def decode(model, paths, itos, size, max_len, device, batch=512, workers=10):
    dl = DataLoader(ImgDS(paths, size), batch_size=batch, shuffle=False, num_workers=workers,
                    pin_memory=True, prefetch_factor=4)
    out = []
    for bi, x in enumerate(dl):
        x = x.to(device, non_blocking=True)
        with torch.autocast('cuda', dtype=torch.bfloat16):
            seq = model.greedy(x, 1, 2, max_len=max_len, prefix=None)  # start from <sos>, no forced prefix
        for ids in seq.cpu().tolist():
            if 2 in ids:
                ids = ids[:ids.index(2)]
            out.append(''.join(itos[i] for i in ids))
        if bi % 50 == 0:
            print(f'batch {bi} decoded {len(out)}', flush=True)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ckpt', required=True)
    ap.add_argument('--data_dir', default='/download_job_code/payload/sandbox/data')
    ap.add_argument('--vocab', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), 'vocab.npy'))
    ap.add_argument('--out', default='submission.csv')
    ap.add_argument('--max_len', type=int, default=420)
    ap.add_argument('--batch', type=int, default=512)
    ap.add_argument('--workers', type=int, default=10)
    ap.add_argument('--sort_by_size', action='store_true', default=True)
    args = ap.parse_args()

    device = 'cuda' if torch.cuda.is_available() else 'cpu'
    itos = list(np.load(args.vocab, allow_pickle=True))
    ck = torch.load(args.ckpt, map_location='cpu')
    aa = ck['args']
    model = Img2InChI(len(itos), encoder_name=aa['encoder'], d=aa['d'], nlayers=aa['nlayers'],
                      dim_ff=aa['dim_ff'], size=aa['size'])
    model.load_state_dict(ck['model'])
    model.to(device).eval()

    sub = pd.read_csv(os.path.join(args.data_dir, 'sample_submission.csv'))
    ids = sub['image_id'].values
    paths = [os.path.join(args.data_dir, 'test', i[0], i[1], i[2], i + '.png') for i in ids]
    order = np.arange(len(ids))
    if args.sort_by_size:
        order = np.argsort([os.path.getsize(p) for p in paths])
    ids_o = ids[order]
    paths_o = [paths[i] for i in order]

    t0 = time.time()
    preds = decode(model, paths_o, itos, aa['size'], args.max_len, device, args.batch, args.workers)
    print(f'decoded {len(preds)} in {time.time()-t0:.0f}s', flush=True)

    sub['InChI'] = sub['image_id'].map(dict(zip(ids_o, preds)))
    assert sub['InChI'].notna().all()

    # Optional chemistry-aware canonicalization (RDKit). Verified on the clean 20k holdout:
    # changes ~0.9% of predictions (chemically-equivalent but non-canonical strings) and lowers
    # mean Levenshtein 2.53 -> 2.35. No information gain; a pure re-serialization of valid InChI.
    try:
        sys.path.insert(0, '/download_job_code/payload/sandbox/workspaces/altair_lambda/shared')
        from inchi_post import canonicalize
        sub['InChI'] = [canonicalize(p) or p for p in sub['InChI'].tolist()]
    except Exception as e:
        print('canonicalization skipped:', e)

    sub.to_csv(args.out, index=False)
    print('wrote', args.out, len(sub))


if __name__ == '__main__':
    main()
